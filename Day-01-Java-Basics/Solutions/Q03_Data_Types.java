public class Q03_Data_Types {

    public static void main(String[] args) {

        byte number = 10;
        short smallNumber = 1000;
        int age = 21;
        long population = 1000000L;

        float price = 99.50f;
        double salary = 25000.75;

        char grade = 'A';
        boolean status = true;

        System.out.println("Byte : " + number);
        System.out.println("Short : " + smallNumber);
        System.out.println("Int : " + age);
        System.out.println("Long : " + population);
        System.out.println("Float : " + price);
        System.out.println("Double : " + salary);
        System.out.println("Char : " + grade);
        System.out.println("Boolean : " + status);

    }
}